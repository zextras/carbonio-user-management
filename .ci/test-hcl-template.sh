# shellcheck disable=SC2317,SC2329
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="${ROOT}/package/carbonio-user-management-hcl"
TEMPLATE_SRC="${ROOT}/package/carbonio-user-management-template.hcl"
FIXTURE="${ROOT}/.ci/fixtures/carbonio-user-management-1.4.9.hcl"

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK:?}"' EXIT

if [[ -z "${CONSUL_TEMPLATE:-}" ]] && command -v consul-template > /dev/null; then
  CONSUL_TEMPLATE="$(command -v consul-template)"
fi
if [[ -n "${CONSUL_TEMPLATE:-}" ]]; then
  echo "Mode: real consul-template (${CONSUL_TEMPLATE})"
else
  CONSUL_TEMPLATE="${WORK}/consul-template-stub"
  cat > "${CONSUL_TEMPLATE}" << 'STUB'
#!/bin/bash
src="" dst=""
while [[ $# -gt 0 ]]; do
  if [[ "$1" == "-template" ]]; then
    src="${2%%:*}"
    dst="${2#*:}"
    shift
  fi
  shift
done
content="$(cat "${src}")"
re='\{\{ or \(env "([A-Z0-9_]+)"\) "([^"]*)" \}\}'
while [[ "${content}" =~ ${re} ]]; do
  val="${!BASH_REMATCH[1]:-}"
  [[ -n "${val}" ]] || val="${BASH_REMATCH[2]}"
  content="${content/"${BASH_REMATCH[0]}"/${val}}"
done
printf '%s\n' "${content}" > "${dst}"
STUB
  chmod 755 "${CONSUL_TEMPLATE}"
  echo "Mode: stub consul-template"
fi
export CONSUL_TEMPLATE

FAILED=0
pass() { echo "PASS: $1"; }
fail() { echo "FAIL: $1"; FAILED=1; }
check() {
  local desc="$1"
  shift
  if "$@"; then pass "${desc}"; else fail "${desc}"; fi
}

SD_DIR=""
fresh() {
  SD_DIR="${WORK}/sd-$1"
  mkdir -p "${SD_DIR}/templates"
  cp "${TEMPLATE_SRC}" "${SD_DIR}/templates/carbonio-user-management-template.hcl"
  export SD_DIR
  LIVE="${SD_DIR}/carbonio-user-management.hcl"
  ENVF="${SD_DIR}/carbonio-user-management.env"
  BAK="${LIVE}.bak"
}
hcl() { "${SCRIPT}" "$@"; }
has() { grep -qE "$1" "$2"; }
mode_of() { [[ "$(stat -c %a "$1")" == "644" ]]; }
edited_fixture() { sed -E "s/^(\s*$1\s*=\s*)\"[^\"]*\"/\1\"$2\"/" "${FIXTURE}"; }

fresh 1
hcl render > /dev/null 2>&1
check "1 render defaults: timeout 1s" has '^\s*timeout\s*=\s*"1s"' "${LIVE}"
check "1 render defaults: interval 5s" has '^\s*interval\s*=\s*"5s"' "${LIVE}"
check "1 render defaults: marker" has 'Generated by carbonio-user-management-hcl' "${LIVE}"
check "1 render defaults: mode 644" mode_of "${LIVE}"

fresh 2
printf '# comment\nCHECK_TIMEOUT="3s"\nBOGUS_KEY=1\n' > "${ENVF}"
hcl render > /dev/null 2> "${WORK}/err2"
rc=$?
check "2 env override: render succeeds" test "${rc}" -eq 0
check "2 env override: timeout 3s" has '^\s*timeout\s*=\s*"3s"' "${LIVE}"
check "2 env override: warning on unknown key" grep -q 'BOGUS_KEY' "${WORK}/err2"

fresh 3
hcl render > /dev/null 2>&1
cp "${LIVE}" "${WORK}/before3"
echo 'CHECK_TIMEOUT=3x' > "${ENVF}"
hcl render > /dev/null 2> "${WORK}/err3"
rc=$?
check "3 invalid value: exit 1" test "${rc}" -eq 1
check "3 invalid value: message" grep -q 'Invalid value for CHECK_TIMEOUT' "${WORK}/err3"
check "3 invalid value: live hcl untouched" cmp -s "${LIVE}" "${WORK}/before3"

fresh 4
CHECK_INTERVAL=9s hcl render > /dev/null 2>&1
check "4 caller env isolated: interval 5s" has '^\s*interval\s*=\s*"5s"' "${LIVE}"

fresh 5
edited_fixture timeout 4s > "${LIVE}"
cp "${LIVE}" "${WORK}/edited5"
hcl migrate > /dev/null 2>&1
check "5 migrate: env has CHECK_TIMEOUT=4s" grep -qx 'CHECK_TIMEOUT=4s' "${ENVF}"
check "5 migrate: exactly one value line" test "$(grep -cvE '^(#|$)' "${ENVF}")" -eq 1
check "5 migrate: env mode 644" mode_of "${ENVF}"
check "5 migrate: .bak equals edited live" cmp -s "${BAK}" "${WORK}/edited5"
hcl render > /dev/null 2>&1
check "5 migrate then render: timeout 4s" has '^\s*timeout\s*=\s*"4s"' "${LIVE}"
cp "${ENVF}" "${WORK}/env5"
echo sentinel > "${BAK}"
out7="$(hcl migrate 2>&1)"
check "7 second migrate: silent" test -z "${out7}"
check "7 second migrate: env unchanged" cmp -s "${ENVF}" "${WORK}/env5"
check "7 second migrate: .bak not rewritten" grep -qx sentinel "${BAK}"

fresh 6
edited_fixture interval 7s > "${LIVE}.rpmsave"
hcl migrate > /dev/null 2>&1
check "6 rpmsave migrate: CHECK_INTERVAL=7s" grep -qx 'CHECK_INTERVAL=7s' "${ENVF}"
check "6 rpmsave migrate: no .bak" test ! -e "${BAK}"
hcl render > /dev/null 2>&1
rm -f "${ENVF:?}"
hcl migrate > /dev/null 2>&1
check "6 env removed after render: rpmsave not migrated again" test ! -e "${ENVF}"

fresh 8
cp "${FIXTURE}" "${LIVE}"
hcl migrate > /dev/null 2>&1
check "8 unedited migrate: no env file" test ! -e "${ENVF}"
check "8 unedited migrate: .bak created" test -f "${BAK}"

fresh 9
echo 'CHECK_TIMEOUT=3s' > "${ENVF}"
hcl show > "${WORK}/show9" 2>&1
check "9 show: key" grep -q 'CHECK_TIMEOUT' "${WORK}/show9"
check "9 show: default and current" grep -qE '│ CHECK_TIMEOUT +│ 1s +│ 3s +│' "${WORK}/show9"

exit "${FAILED}"
